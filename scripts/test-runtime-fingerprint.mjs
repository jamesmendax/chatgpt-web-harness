import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { writeBuildManifest } from './write-build-manifest.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const tmp=await fs.mkdtemp(path.join(os.tmpdir(),'runtime-fingerprint-'));
await fs.cp(path.join(root,'dist'),path.join(tmp,'dist'),{recursive:true});
await fs.writeFile(path.join(tmp,'package.json'),JSON.stringify({type:'module',version:'0.0.0-fixture'}));
const config=path.join(tmp,'plugins.json');
await fs.writeFile(config,JSON.stringify({schema_version:2,skills:[]}));
process.env.CHATGPT_PLUGINS_CONFIG=config;
delete process.env.HARNESS_APP_VERSION;
const before=writeBuildManifest(tmp);
const {getRuntimeManifest}=await import(pathToFileURL(path.join(tmp,'dist/lib/runtime-manifest.js')).href);
assert.equal(getRuntimeManifest(true).stale_build,false);
assert.equal(getRuntimeManifest().app_version,'0.0.0-fixture');
const target=path.join(tmp,'dist/lib/tool-result.js');
const stat=await fs.stat(target),original=await fs.readFile(target);
await fs.utimes(target,new Date(),new Date());
assert.equal(writeBuildManifest(tmp).content_sha256,before.content_sha256,'mtime alone cannot change build identity');
await fs.appendFile(target,'\n// fixture content changed\n');
await fs.utimes(target,stat.atime,stat.mtime);
assert.equal(getRuntimeManifest(true).stale_build,true,'another module must be checked even when its mtime is preserved');
await fs.writeFile(target,original);
assert.equal(getRuntimeManifest(true).stale_build,false);
await fs.unlink(target);
assert.equal(getRuntimeManifest(true).stale_build,true,'a missing module must fail the content check');
console.log('PASS deterministic content identity, preserved-mtime changes, missing module, package version');
