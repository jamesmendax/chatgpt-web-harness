export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export function assertTestManifest(base = root, full = fullTests, daily = dailyTests) {
  if (new Set(full).size !== full.length || new Set(daily).size !== daily.length) throw new Error("Duplicate test entry");
  for (const test of daily) if (!full.includes(test)) throw new Error(`Daily test absent from full suite: ${test}`);
  for (const test of full) if (!fs.existsSync(path.join(base,test))) throw new Error(`Required test is missing: ${test}`);
  for (const test of [...full, ...daily]) if (historicalTests.includes(test)) throw new Error(`Retired feature test in active suite: ${test}`);
}
const sourceTypeScriptTests = new Set([
  "scripts/test-binary-upload-integrity.mjs",
  "scripts/test-runtime-race-repairs.mjs",
  "scripts/test-goal-run-crossprocess.mjs",
  "scripts/test-intent-reference.mjs",
  "scripts/test-result-phases.mjs",
  "scripts/test-retired-relay-compat.mjs",
]);
export function nodeArgs(test) { return sourceTypeScriptTests.has(test) ? ["--import", "tsx", path.join(root,test)] : [path.join(root,test)]; }
export async function runTest(test, env = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, nodeArgs(test), { cwd: root, env: {...process.env,...env}, stdio: "inherit" });
    child.once("error", reject);
    child.once("close", code => code === 0 ? resolve() : reject(new Error(`${test} exit ${code}`)));
  });
}
if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const mode = process.argv[2] || "daily";
  if (!["daily", "full", "check"].includes(mode)) throw new Error("Expected daily, full, or check");
  assertTestManifest();
  if (mode !== "check") for (const test of mode === "daily" ? dailyTests : fullTests) { console.log(`\n--- ${test} ---`); await runTest(test); }
}
