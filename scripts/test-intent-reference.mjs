import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { EffectiveToolRegistry } from "../src/lib/effective-tool-registry.ts";
import { InvocationGateway } from "../src/lib/invocation-gateway.ts";
import { executionContractStatePath } from "../src/lib/execution-contract.ts";
import { createGoal } from "../src/lib/goals.ts";
import { createRuntimeScope, runWithRuntimeScope } from "../src/lib/runtime-scope.ts";
const temp = await fs.mkdtemp(path.join(os.tmpdir(), "wh-intent-reference-"));
const saved = { home: process.env.CODEX_HOME, account: process.env.HARNESS_ACCOUNT_ID, relay: process.env.HARNESS_RELAY_ENABLED };
try {
  process.env.CODEX_HOME = path.join(temp, "state"); process.env.HARNESS_ACCOUNT_ID = "account-a";
  const registry = new EffectiveToolRegistry("full"); let calls = 0, lastArgs;
  registry.register(registry.prepare("fixture_write", { inputSchema: {}, annotations: { readOnlyHint: false } }, async args => { calls++; lastArgs = args; return { content: [{type:"text",text:"done"}] }; }));
  const gateway = new InvocationGateway(registry, { workspaceRoot: temp, projectRoots: [temp] });
  const extra = { sessionId: "session-a", requestId: "fixture", signal: new AbortController().signal };
  const model = { intent_revision: 1, objective:"exercise fixture", scope:["isolated"], out_of_scope:[], deliverables:["result"], success_criteria:["done"], constraints:[], protected_resources:[], known_facts:[], assumptions:[], delegated_decisions:[], remaining_nonblocking_uncertainties:[], closure_items:[], ambiguities:[], clarification_round:0, questions_in_round:0, resolution_mode:"none" };
  let serial = 0;
  const invoke = (intent, request = extra, target = gateway) => target.invoke("fixture_write", [{ payload:"ok", _intent: intent }, { ...request, requestId: `request-${++serial}` }]);
  const first = await invoke(JSON.stringify(model)); assert.equal(calls, 1); assert.equal(lastArgs._intent, undefined);
  const file = executionContractStatePath(temp, "session-a"), before = await fs.readFile(file, "utf8");
  const accepted = JSON.parse(before);
  const disclosed = first._meta["harness/intent_reference"];
  assert.equal(disclosed.expires_at, accepted.expires_at);
  assert.equal(disclosed.reference.requirement_hash, accepted.requirement_hash);
  const ref = JSON.stringify({ reference: disclosed.reference });
  assert.ok(first.content.some(item => item.type === "text" && item.text.includes(ref)), "model-visible result must include the exact reference");
  const referenceResult = await invoke(ref); assert.equal(calls, 2, JSON.stringify(referenceResult)); assert.equal(await fs.readFile(file, "utf8"), before, "reference must not renew expiry");
  await invoke(JSON.stringify({ reference:{ intent_revision: 1, requirement_hash: "a".repeat(64) } })); assert.equal(calls, 2);
  await invoke(JSON.stringify({ reference:{ intent_revision: 2, requirement_hash: accepted.requirement_hash } })); assert.equal(calls, 2);
  await invoke(JSON.stringify({ reference:{ intent_revision: 1, requirement_hash: accepted.requirement_hash, extra:true } })); assert.equal(calls, 2);
  await invoke(ref, { ...extra, sessionId: "session-b" }); assert.equal(calls, 2);
  process.env.HARNESS_ACCOUNT_ID = "account-b"; await invoke(ref); assert.equal(calls, 2);
  process.env.HARNESS_ACCOUNT_ID = "account-a";
  const other = new InvocationGateway(registry, { workspaceRoot: path.join(temp, "other"), projectRoots:[temp] });
  await invoke(ref, extra, other); assert.equal(calls, 2);
  await fs.writeFile(file, JSON.stringify({ ...accepted, scope_binding: undefined }));
  await invoke(ref); assert.equal(calls, 2, "legacy unbound state must require the full form");
  await invoke(JSON.stringify(model)); assert.equal(calls, 3, "full form can rebind the legacy state");
  await invoke(ref); assert.equal(calls, 4);
  await fs.writeFile(file, JSON.stringify({ ...accepted, expires_at:"2000-01-01T00:00:00.000Z" }));
  await invoke(ref); assert.equal(calls, 4);
  const goalWorkspace = path.join(temp, "goal"); await fs.mkdir(goalWorkspace);
  const goalGateway = new InvocationGateway(registry, {workspaceRoot:goalWorkspace,projectRoots:[goalWorkspace]});
  const goalExtra = {...extra, sessionId:"goal-session"};
  const noGoal = await invoke(JSON.stringify(model), goalExtra, goalGateway); assert.equal(calls, 5);
  const noGoalRef = JSON.stringify({reference:noGoal._meta["harness/intent_reference"].reference});
  const scope = createRuntimeScope({workspaceRoot:goalWorkspace, projectRoots:[goalWorkspace]}, {sessionId:"goal-session"});
  await runWithRuntimeScope(scope, () => createGoal(goalWorkspace, { objective:"isolated Goal", success_criteria:[{name:"done",passed:false}] }));
  await invoke(noGoalRef, goalExtra, goalGateway); assert.equal(calls, 5, "reference must not cross a Goal transition");
  await invoke(JSON.stringify(model), goalExtra, goalGateway); assert.equal(calls, 6);
  process.env.HARNESS_RELAY_ENABLED = "true";
  const blocked = await invoke(undefined, goalExtra, goalGateway);
  assert.equal(blocked.structuredContent.data.error_code, "REQUIREMENT_CONTRACT_REQUIRED");
  assert.equal(calls, 6, "retired Relay flag must not bypass the intent gate");
  console.log("PASS model-visible reference, scope, revision, malformed input, legacy rebind and expiry; no expiry renewal");
} finally {
  for (const [key, value] of [["CODEX_HOME",saved.home],["HARNESS_ACCOUNT_ID",saved.account],["HARNESS_RELAY_ENABLED",saved.relay]]) if (value === undefined) delete process.env[key]; else process.env[key] = value;
  await fs.rm(temp, { recursive:true, force:true });
}
